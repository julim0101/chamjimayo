# ============================================================ 판정 함수


def is_directive(text: str) -> bool:
    """지시·명령·기한 압박 표현 포함 여부."""
    return any(p.search(text) for p in DIRECTIVE_PATTERNS)


def is_rebuke_question(text: str) -> bool:
    """질책성 추궁 여부."""
    return any(p.search(text) for p in REBUKE_QUESTION_PATTERNS)


def is_apology(text: str) -> bool:
    """사과·수용·복종 표현 포함 여부."""
    return any(p.search(text) for p in APOLOGY_PATTERNS)


def toxic_hits(text: str) -> list[tuple[str, str]]:
    """(카테고리, 매칭어) 목록. 근거 하이라이트에 사용."""
    hits: list[tuple[str, str]] = []
    for cat, words in TOXIC_LEXICON.items():
        for w in words:
            if w in text:
                hits.append((cat, w))
    return hits


def lexicon_toxicity(text: str) -> float:
    """어휘 기반 독성 점수 (0.0~1.0). 학습 모델 미가용 시 폴백.

    단일 비하 표현 1건 ≈ 0.62, 욕설 1건 ≈ 0.75,
    복수 매칭 시 체감 가중으로 1.0에 수렴한다.
    """
    hits = toxic_hits(text)
    if not hits:
        return 0.0
    score, seen = 0.0, set()
    for cat, w in hits:
        if w in seen:
            continue
        seen.add(w)
        score += TOXIC_WEIGHTS.get(cat, 0.5)
    return min(1.0, 1 - pow(0.25, score))


def subtle_hits(text: str) -> list[str]:
    """Tier 3 정황 후보 카테고리 목록."""
    return [cat for cat, pats in SUBTLE_PATTERNS.items() if any(p.search(text) for p in pats)]


def labor_violation_hits(text: str) -> list[tuple[str, str]]:
    """부수 법위반 단서 (위반 유형, 근거 조항) 목록."""
    out: list[tuple[str, str]] = []
    for name, spec in LABOR_VIOLATION_PATTERNS.items():
        if any(p.search(text) for p in spec["patterns"]):
            out.append((name, spec["law"]))
    return out
